-- Thimar authentication boundary v2 — PREPARED, NOT APPLIED, NOT TESTED.
--
-- Review notes are inline. Nothing here has been executed against staging or production.
--
-- Password format today (src/lib/password.ts): sha256hex(salt || ':' || password),
-- verified server-side here so password_hash/password_salt never leave Postgres.
--
-- v2 adds: bounded search_path, explicit SECURITY DEFINER checks, per-account and per-IP
-- rate limiting, bcrypt upgrade path, and safe handling of banned/inactive/unknown accounts.

begin;

create extension if not exists pgcrypto;

-- Opaque 12-hour application sessions. Store only SHA-256 token digests.
create table if not exists public.thimar_call_sessions (
  token_hash text primary key,
  account_id text not null references public.thimar_accounts(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz
);
create index if not exists thimar_call_sessions_account_idx on public.thimar_call_sessions(account_id, expires_at);
alter table public.thimar_call_sessions enable row level security;
revoke all on public.thimar_call_sessions from public, anon, authenticated;

-- Server-only signaling inbox. Clients never access this table directly; the
-- authenticated Edge Function validates the opaque session and call membership.
create table if not exists public.thimar_call_signals (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.thimar_calls(id) on delete cascade,
  sender_id text not null references public.thimar_accounts(id) on delete cascade,
  recipient_id text not null references public.thimar_accounts(id) on delete cascade,
  kind text not null check (kind in ('invite','accept','decline','offer','answer','ice','hangup')),
  payload jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists thimar_call_signals_recipient_idx
  on public.thimar_call_signals(recipient_id, id);
create index if not exists thimar_call_signals_call_recipient_idx
  on public.thimar_call_signals(call_id, recipient_id, id);
alter table public.thimar_call_signals enable row level security;
revoke all on public.thimar_call_signals from public, anon, authenticated;

-- Resolve the custom application session from a trusted PostgREST request header.
-- This lets RLS identify app accounts without treating an opaque token as a Supabase JWT.
create or replace function public.thimar_session_account_id()
returns text
language plpgsql
stable
security definer
set search_path = pg_catalog, extensions, public, pg_temp
as $
declare
  raw_token text;
  account_key text;
begin
  begin
    raw_token := current_setting('request.headers', true)::jsonb ->> 'x-thimar-session';
  exception when others then
    return null;
  end;
  if raw_token is null or length(raw_token) <> 64 then return null; end if;
  select s.account_id into account_key
    from public.thimar_call_sessions s
    join public.thimar_accounts a on a.id = s.account_id
   where s.token_hash = encode(digest(raw_token, 'sha256'), 'hex')
     and s.expires_at > now()
     and s.revoked_at is null
     and a.status = 'active'
     and coalesce(a.banned, false) = false
   limit 1;
  return account_key;
end;
$;

create or replace function public.thimar_session_role()
returns text
language sql
stable
security definer
set search_path = pg_catalog, extensions, public, pg_temp
as $
  select a.type
    from public.thimar_accounts a
   where a.id = public.thimar_session_account_id()
   limit 1
$;

revoke all on function public.thimar_session_account_id() from public;
revoke all on function public.thimar_session_role() from public;
grant execute on function public.thimar_session_account_id() to anon, authenticated;
grant execute on function public.thimar_session_role() to anon, authenticated;


