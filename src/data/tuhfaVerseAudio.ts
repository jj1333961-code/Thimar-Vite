export function tuhfaVerseWindow(reciter: TuhfaVerseReciter, verse: number): [number, number] {
  const start = reciter.starts[verse - 1] ?? 0;
  const end = reciter.starts[verse] ?? reciter.duration;
  return [Math.max(0, start), Math.max(start + 1, end)];
}
