const normalize = (value: string) =>
  value
    .replace(/[\u064B-\u0652\u0670\u06D6-\u06ED]/g, "")
    .replace(/[إأآا]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[^\u0621-\u064Aa-zA-Z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** بحث حرفي أو بكلمة أو بعدة كلمات في نص الحديث وموضوعه وشرحه. */
export function searchHadiths(query: string): HadithEntry[] {
  const needle = normalize(query);
  if (!needle) return hadiths;
  const words = needle.split(" ").filter(Boolean);
  return hadiths.filter((hadith) => {
    const haystack = normalize(
      `${hadith.title} ${hadith.text} ${hadith.topic} ${hadith.explanation} ${hadith.source}`,
    );
    return words.every((word) => haystack.includes(word));
  });
}

export function getHadith(id: string): HadithEntry | undefined {
  return hadiths.find((item) => item.id === id);
}
